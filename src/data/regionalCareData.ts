// Helper to find region by province or region name
export function findRegionByProvinceOrName(searchTerm: string): RegionalCareRegionData {
  const term = searchTerm.toLowerCase().trim();
  const found = REGIONAL_CARE_DATA.find((r) => {
    if (r.regionName.toLowerCase().includes(term) || r.regionId.toLowerCase().includes(term)) {
      return true;
    }
    return r.provinces.some((p) => p.toLowerCase().includes(term));
  });
  return found || REGIONAL_CARE_DATA[0]; // Default to Ege Bölgesi
}

// Get care plan for a specific region and month (0-11)
export function getRegionalCarePlan(region: RegionalCareRegionData, monthIndex: number): RegionalMonthCare {
  const safeMonth = Math.max(0, Math.min(11, monthIndex));
  return region.annualSchedule[safeMonth] || region.annualSchedule[0];
}
