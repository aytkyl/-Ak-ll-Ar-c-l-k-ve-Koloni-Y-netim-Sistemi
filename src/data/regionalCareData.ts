// Helper to build a comprehensive month plan
function createMonthCare(
  monthIndex: number,
  season: "İlkbahar" | "Yaz" | "Sonbahar" | "Kış",
  phenology: string,
  headline: string,
  checkpoints: string[],
  feedingType: "Teşvik Şerbeti (1:1)" | "Kış Şerbeti (2:1)" | "Arı Keki / Fondan" | "Besleme Yapılmaz (Nektar Akımı)" | "Polen İkamesi",
  feedingDetails: string,
  varroa: string,
  frameSuper: string,
  entrance: string,
  urgentAlerts: string[],
  intervalDays: number,
  intervalText: string,
  primaryGoal: string,
  nextCheckpoints: string[],
  equipment: string[],
  criticalAlert?: string
): RegionalMonthCare {
  return {
    monthIndex,
    monthName: MONTH_NAMES[monthIndex],
    season,
    phenologySummary: phenology,
    currentCare: {
      headline,
      inspectionCheckpoints: checkpoints,
      feedingAdvice: { type: feedingType, details: feedingDetails },
      varroaAndHealth: varroa,
      frameAndSuperAction: frameSuper,
      hiveEntranceAndVentilation: entrance,
      urgentAlerts
    },
    nextCare: {
      intervalDays,
      intervalText,
      primaryGoal,
      checkpoints: nextCheckpoints,
      equipmentToBring: equipment,
      criticalAlert
    }
  };
}

